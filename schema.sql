CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  email VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS designs (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  title VARCHAR(120) NOT NULL,
  is_public BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS design_objects (
  id INT AUTO_INCREMENT PRIMARY KEY,
  design_id INT NOT NULL,
  shape VARCHAR(20) NOT NULL,
  pos_x DOUBLE DEFAULT 0, pos_y DOUBLE DEFAULT 0, pos_z DOUBLE DEFAULT 0,
  rot_x DOUBLE DEFAULT 0, rot_y DOUBLE DEFAULT 0, rot_z DOUBLE DEFAULT 0,
  scale_x DOUBLE DEFAULT 1, scale_y DOUBLE DEFAULT 1, scale_z DOUBLE DEFAULT 1,
  color VARCHAR(7) DEFAULT '#cccccc',
  FOREIGN KEY (design_id) REFERENCES designs(id) ON DELETE CASCADE
);